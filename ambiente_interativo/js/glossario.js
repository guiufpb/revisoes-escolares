const ID_DIALOGO = 'dialogo-glossario';
let ultimoAcionador = null;

function normalizar(valor) {
  return String(valor || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
}

function escaparExpressao(valor) {
  return valor.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function idsValidos(ids) {
  const valores = Array.isArray(ids) ? ids : Object.keys(glossario);
  return [...new Set(valores)].filter((id) => Boolean(glossario[id]));
}

function obter(id) {
  return glossario[id] || null;
}

function encontrarNoTexto(texto, ids) {
  const textoNormalizado = normalizar(texto);
  return idsValidos(ids).filter((id) => {
    const palavra = normalizar(glossario[id].palavra);
    const expressao = new RegExp('(^|[^a-z0-9])' + escaparExpressao(palavra) + '([^a-z0-9]|$)');
    return expressao.test(textoNormalizado);
  });
}

function encontrarEmTextos(textos, ids) {
  const encontrados = [];
  (Array.isArray(textos) ? textos : [textos]).forEach((texto) => {
    encontrarNoTexto(texto, ids).forEach((id) => {
      if (!encontrados.includes(id)) encontrados.push(id);
    });
  });
  return encontrados;
}

function criarBotao(id, rotulo) {
  const verbete = obter(id);
  if (!verbete) return null;
  const botao = document.createElement('button');
  botao.type = 'button';
  botao.className = 'palavra-glossario';
  botao.dataset.palavra = id;
  botao.setAttribute('aria-haspopup', 'dialog');
  botao.setAttribute('aria-controls', ID_DIALOGO);
  botao.setAttribute('aria-label', 'Ver significado de ' + verbete.palavra);
  botao.textContent = rotulo || verbete.palavra;
  return botao;
}

function renderizarTexto(alvo, texto, ids) {
  if (!alvo) return;
  const permitidos = idsValidos(ids);
  const porPalavra = new Map(permitidos.map((id) => [normalizar(glossario[id].palavra), id]));
  const palavras = permitidos.map((id) => escaparExpressao(glossario[id].palavra));
  alvo.replaceChildren();
  if (!palavras.length) {
    alvo.textContent = String(texto || '');
    return;
  }

  const expressao = new RegExp('\\b(' + palavras.join('|') + ')\\b', 'giu');
  let inicio = 0;
  let resultado;
  while ((resultado = expressao.exec(String(texto || ''))) !== null) {
    if (resultado.index > inicio) {
      alvo.appendChild(document.createTextNode(String(texto).slice(inicio, resultado.index)));
    }
    const id = porPalavra.get(normalizar(resultado[0]));
    alvo.appendChild(criarBotao(id, resultado[0]));
    inicio = expressao.lastIndex;
  }
  if (inicio < String(texto || '').length) {
    alvo.appendChild(document.createTextNode(String(texto).slice(inicio)));
  }
}

function criarAtalhos(ids) {
  const validos = idsValidos(ids);
  if (!validos.length) return null;
  const recipiente = document.createElement('aside');
  const rotulo = document.createElement('span');
  recipiente.className = 'atalhos-glossario';
  recipiente.setAttribute('aria-label', 'Ajuda com palavras difíceis');
  rotulo.textContent =
    validos.length === 1 ? 'Palavra que pode ajudar:' : 'Palavras que podem ajudar:';
  recipiente.appendChild(rotulo);
  validos.forEach((id) => recipiente.appendChild(criarBotao(id)));
  return recipiente;
}

function criarDialogo() {
  let dialogo = document.getElementById(ID_DIALOGO);
  if (dialogo) return dialogo;

  dialogo = document.createElement('dialog');
  const cartao = document.createElement('div');
  const cabecalho = document.createElement('header');
  const titulo = document.createElement('h2');
  const fechar = document.createElement('button');
  const corpo = document.createElement('div');

  dialogo.id = ID_DIALOGO;
  dialogo.className = 'dialogo-glossario';
  dialogo.setAttribute('aria-labelledby', 'titulo-dialogo-glossario');
  cartao.className = 'cartao-dialogo-glossario';
  cabecalho.className = 'cabecalho-dialogo-glossario';
  titulo.id = 'titulo-dialogo-glossario';
  fechar.type = 'button';
  fechar.className = 'fechar-dialogo-glossario';
  fechar.setAttribute('aria-label', 'Fechar explicação');
  fechar.textContent = '×';
  corpo.id = 'corpo-dialogo-glossario';
  corpo.className = 'corpo-dialogo-glossario';
  fechar.addEventListener('click', () => dialogo.close());
  dialogo.addEventListener('click', (evento) => {
    if (evento.target === dialogo) dialogo.close();
  });
  dialogo.addEventListener('close', () => {
    if (ultimoAcionador && ultimoAcionador.isConnected) ultimoAcionador.focus();
    ultimoAcionador = null;
  });
  cabecalho.append(titulo, fechar);
  cartao.append(cabecalho, corpo);
  dialogo.appendChild(cartao);
  document.body.appendChild(dialogo);
  return dialogo;
}

function adicionarVerbete(corpo, id, mostrarTitulo) {
  const verbete = obter(id);
  if (!verbete) return;
  const secao = document.createElement('section');
  const titulo = document.createElement('h3');
  const significado = document.createElement('p');
  const exemplo = document.createElement('p');
  secao.className = 'verbete-glossario';
  titulo.textContent = verbete.palavra;
  significado.append(
    document.createElement('strong'),
    document.createTextNode(verbete.significado)
  );
  significado.querySelector('strong').textContent = 'Significado: ';
  exemplo.append(document.createElement('strong'), document.createTextNode(verbete.exemplo));
  exemplo.querySelector('strong').textContent = 'Exemplo: ';
  if (mostrarTitulo) secao.appendChild(titulo);
  secao.append(significado, exemplo);
  corpo.appendChild(secao);
}

function abrirLista(ids, acionador, titulo) {
  const validos = idsValidos(ids);
  if (!validos.length) return false;
  const dialogo = criarDialogo();
  const corpo = dialogo.querySelector('#corpo-dialogo-glossario');
  dialogo.querySelector('#titulo-dialogo-glossario').textContent =
    titulo || (validos.length === 1 ? glossario[validos[0]].palavra : 'Palavras desta página');
  corpo.replaceChildren();
  validos.forEach((id) => adicionarVerbete(corpo, id, validos.length > 1 || Boolean(titulo)));
  ultimoAcionador = acionador || document.activeElement;
  if (typeof dialogo.showModal === 'function') dialogo.showModal();
  else dialogo.setAttribute('open', '');
  dialogo.querySelector('.fechar-dialogo-glossario').focus();
  return true;
}

function termosDaPagina(livro, pagina) {
  const porPagina = livro && livro.glossarioPorPagina;
  const ids = porPagina && porPagina[String(pagina)];
  return idsValidos(Array.isArray(ids) ? ids : []);
}

function atualizarBotaoPagina(botao, livro, pagina) {
  if (!botao) return [];
  const ids = termosDaPagina(livro, pagina);
  botao.hidden = ids.length === 0;
  botao.disabled = ids.length === 0;
  botao.dataset.glossarioLista = ids.join(',');
  botao.textContent = '📘 Palavras desta página' + (ids.length > 1 ? ' (' + ids.length + ')' : '');
  return ids;
}

document.addEventListener('click', (evento) => {
  const botaoPalavra = evento.target.closest('[data-palavra]');
  if (botaoPalavra) {
    abrirLista([botaoPalavra.dataset.palavra], botaoPalavra);
    return;
  }
  const botaoLista = evento.target.closest('[data-glossario-lista]');
  if (botaoLista && botaoLista.dataset.glossarioLista) {
    abrirLista(botaoLista.dataset.glossarioLista.split(','), botaoLista, 'Palavras desta página');
  }
});

window.GlossarioRevisoes = Object.freeze({
  glossario,
  obter,
  encontrarNoTexto,
  encontrarEmTextos,
  criarBotao,
  criarAtalhos,
  renderizarTexto,
  abrirLista,
  termosDaPagina,
  atualizarBotaoPagina,
});
